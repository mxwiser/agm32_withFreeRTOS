"""Generate compact ASCII UI fonts from the bundled LVGL Montserrat fonts."""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


def generate(size):
    source = ROOT / f"lvgl-v9.6.0-lite/src/font/lv_font_montserrat_{size}.c"
    target = ROOT / f"user/user_fonts/font_dashboard_{size}.c"
    text = source.read_text(encoding="utf-8")

    start = text.index('    /* U+00B0')
    end = text.index('\n};', start)
    text = text[:start] + text[end:]
    pattern = r'(static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc\[\] = \{\n)(.*?)(\n\};)'
    match = re.search(pattern, text, re.DOTALL)
    if not match:
        raise RuntimeError(f"Missing glyph descriptors in {source}")
    rows = match.group(2).splitlines()
    if len(rows) < 96 or "id = 0 reserved" not in rows[0]:
        raise RuntimeError(f"Unexpected glyph descriptors in {source}")
    text = text[:match.start(2)] + '\n'.join(rows[:96]).rstrip(',') + text[match.end(2):]
    text, count = re.subn(r'static const uint16_t unicode_list_1\[\] = \{.*?\};\n\n', '', text, flags=re.DOTALL)
    if count != 1:
        raise RuntimeError(f"Unexpected Unicode list in {source}")
    text, count = re.subn(r'    \},\n    \{\n        \.range_start = 176,.*?\n    \}\n\};',
                          '    }\n};', text, count=1, flags=re.DOTALL)
    if count != 1:
        raise RuntimeError(f"Unexpected character map in {source}")
    text = text.replace('.cmap_num = 2,', '.cmap_num = 1,')
    text = text.replace(f'lv_font_montserrat_{size}', f'font_dashboard_{size}')
    text = text.replace(f'LV_FONT_MONTSERRAT_{size}', f'FONT_DASHBOARD_{size}')
    text = text.replace('static LV_ATTRIBUTE_LARGE_CONST const uint8_t glyph_bitmap[]',
                        'static const uint8_t glyph_bitmap[] __attribute__((section(".flash.font")))')
    text = f'/* Generated by tools/make_dashboard_fonts.py; ASCII 0x20-0x7e. */\n' + text
    target.write_text(text, encoding='utf-8', newline='\n')
    print(f"Generated {target}")


if __name__ == '__main__':
    for font_size in (12, 20):
        generate(font_size)
