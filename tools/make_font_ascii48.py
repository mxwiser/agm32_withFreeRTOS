"""Generate the bike display's ASCII font from the bundled LVGL font."""
from pathlib import Path
import re

root = Path(__file__).resolve().parents[1]
source = root / "lvgl-v9.6.0-lite/src/font/lv_font_montserrat_48.c"
target = root / "user/font_bike_48.c"
text = source.read_text(encoding="utf-8")

# ASCII occupies glyph IDs 1..95; bitmap entries are stored in ID order.
start = text.index('    /* U+00B0')
end = text.index('\n};', start)
text = text[:start] + text[end:]
pattern = r'(static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc\[\] = \{\n)(.*?)(\n\};)'
match = re.search(pattern, text, re.DOTALL)
if not match:
    raise RuntimeError("Could not find glyph descriptors")
rows = match.group(2).splitlines()
if len(rows) < 96 or "id = 0 reserved" not in rows[0]:
    raise RuntimeError("Unexpected source font layout")
text = text[:match.start(2)] + '\n'.join(rows[:96]).rstrip(',') + text[match.end(2):]
text, count = re.subn(r'static const uint16_t unicode_list_1\[\] = \{.*?\};\n\n', '', text, flags=re.DOTALL)
if count != 1:
    raise RuntimeError("Unexpected Unicode list")
text, count = re.subn(r'    \},\n    \{\n        \.range_start = 176,.*?\n    \}\n\};',
                      '    }\n};', text, count=1, flags=re.DOTALL)
if count != 1:
    raise RuntimeError("Unexpected character map")
text = text.replace('.cmap_num = 2,', '.cmap_num = 1,')
text = text.replace('lv_font_montserrat_48', 'lv_font_bike_48')
text = text.replace('LV_FONT_MONTSERRAT_48', 'LV_FONT_BIKE_48')
text = text.replace('static LV_ATTRIBUTE_LARGE_CONST const uint8_t glyph_bitmap[]',
                    'static const uint8_t glyph_bitmap[] __attribute__((section(".flash.font")))')
text = '/* Generated by tools/make_font_ascii48.py; ASCII 0x20-0x7e. */\n' + text
target.write_text(text, encoding='utf-8', newline='\n')
print(f"Generated {target} from {source}")
