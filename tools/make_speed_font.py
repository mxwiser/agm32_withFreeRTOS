"""Generate a compact 58 px digit font from the bundled 48 px LVGL font.

Requires Pillow. The output keeps 4-bit anti-aliasing and lives in Flash.
"""
from pathlib import Path
import re
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "lvgl-v9.6.0-lite/src/font/lv_font_montserrat_48.c"
TARGET = ROOT / "user/user_fonts/font_speed_58.c"
SCALE = 58 / 48

source = SOURCE.read_text(encoding="utf-8")
bitmap_section = source.split("const uint8_t glyph_bitmap[]", 1)[1].split("{", 1)[1].split("};", 1)[0]
bitmap_section = re.sub(r"/\*.*?\*/", "", bitmap_section, flags=re.DOTALL)
bitmap = bytes(int(value, 16) for value in re.findall(r"0x([0-9a-fA-F]{1,2})", bitmap_section))
glyph_section = source.split("static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {", 1)[1].split("};", 1)[0]
glyphs = re.findall(r"\{([^{}]*\.bitmap_index[^{}]*)\}", glyph_section)
if len(glyphs) < 59:
    raise RuntimeError("Unexpected font descriptor layout")

output = bytearray()
descriptors = ["    {0}, /* reserved */"]
for char in "0123456789":
    values = {key: int(value) for key, value in re.findall(r"\.(\w+)\s*=\s*(-?\d+)", glyphs[ord(char) - 31])}
    width, height = values["box_w"], values["box_h"]
    image = Image.new("L", (width, height))
    pixels = image.load()
    for y in range(height):
        for x in range(width):
            pos = y * width + x
            byte = bitmap[values["bitmap_index"] + pos // 2]
            pixels[x, y] = ((byte >> (4 if pos % 2 == 0 else 0)) & 0x0f) * 17
    new_w, new_h = round(width * SCALE), round(height * SCALE)
    image = image.resize((new_w, new_h), Image.Resampling.LANCZOS)
    alpha = [(value + 8) // 17 for value in image.tobytes()]
    index = len(output)
    for i in range(0, len(alpha), 2):
        output.append((alpha[i] << 4) | (alpha[i + 1] if i + 1 < len(alpha) else 0))
    descriptors.append(
        "    {.bitmap_index = %d, .adv_w = %d, .box_w = %d, .box_h = %d, .ofs_x = %d, .ofs_y = %d}, /* %s */"
        % (index, round(values["adv_w"] * SCALE), new_w, new_h,
           round(values["ofs_x"] * SCALE), round(values["ofs_y"] * SCALE), char)
    )

rows = ["    " + ", ".join(f"0x{value:02x}" for value in output[i:i + 16]) + ","
        for i in range(0, len(output), 16)]
result = '''/* Generated by tools/make_speed_font.py: 58 px digits, 4-bit alpha. */
#include "lvgl.h"

static const uint8_t glyph_bitmap[] __attribute__((section(".flash.font"))) = {
%s
};
static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {
%s
};
static const lv_font_fmt_txt_cmap_t cmaps[] = {
    {.range_start = 48, .range_length = 10, .glyph_id_start = 1,
     .unicode_list = NULL, .glyph_id_ofs_list = NULL, .list_length = 0,
     .type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY}
};
static const lv_font_fmt_txt_dsc_t font_dsc = {
    .glyph_bitmap = glyph_bitmap, .glyph_dsc = glyph_dsc, .cmaps = cmaps,
    .kern_dsc = NULL, .kern_scale = 0, .cmap_num = 1, .bpp = 4,
    .kern_classes = 0, .bitmap_format = 0
};
const lv_font_t font_speed_58 = {
    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,
    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,
    .line_height = 63, .base_line = 11, .cap_height = 41, .x_height = 30,
    .subpx = LV_FONT_SUBPX_NONE, .underline_position = -5,
    .underline_thickness = 2, .static_bitmap = 1,
    .dsc = &font_dsc, .fallback = NULL, .user_data = NULL
};
''' % ("\n".join(rows), "\n".join(descriptors))
TARGET.write_text(result, encoding="utf-8", newline="\n")
print(f"Generated {TARGET} ({len(output)} bitmap bytes)")
